#!/usr/bin/env python3
"""Author a 5x7 bitmap font as ASCII art and emit it as a Rust table.

Art is 7 rows of 5 chars; '#' is ink. Encoded as 5 bytes, one per COLUMN,
bit 0 = top row. That column-major layout is what the blitter wants.
"""
import sys

G = {}


def g(ch, art):
    # Drop only the leading newline from the literal; trailing blank rows are GLYPH DATA
    # (descenders, the gap under a comma) and stripping them silently shifts every row up.
    rows = art.split("\n")[1:]
    rows = [r.ljust(5)[:5] for r in rows[:7]]
    while len(rows) < 7:
        rows.append("     ")
    cols = []
    for c in range(5):
        b = 0
        for r in range(7):
            if rows[r][c] == "#":
                b |= 1 << r
        cols.append(b)
    G[ch] = cols


